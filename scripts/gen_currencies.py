"""gen_currencies.py -- src/model/currencies_gen.h : the client's own row order and labels of Status -> Currencies
(mode 1, packet 0x113, 99 rows) and Currencies 2 (mode 2, packet 0x118, 97 rows).

Source : the static RE of the client's two row tables (TABLE1 0x056C7390 / TABLE2 0x056C76A8 -- byte-identical in the
June and November 2026 clients), transcribed with their EN labels from the d_msg DAT (ROM/165/77.DAT) into
docs/notes/status-panels-b-re-2026-11-18.md, appendices 1 and 2. Usage : python scripts/gen_currencies.py
"""
import os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
NOTES = os.path.join(ROOT, 'docs', 'notes', 'status-panels-b-re-2026-11-18.md')
OUT = os.path.join(ROOT, 'src', 'model', 'currencies_gen.h')


def table(lines, start):
    rows = []
    for ln in lines[start:]:
        m = re.match(r'\|\s*(\d+)\s*\|[^|]*\|[^|]*\|[^|]*\|[^|]*\|\s*(.*?)\s*\|\s*$', ln)
        if m:
            rows.append((int(m.group(1)), m.group(2)))
        elif rows and not ln.startswith('|'):
            break
    return rows


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    lines = open(NOTES, encoding='utf-8').read().splitlines()
    a1 = next(i for i, l in enumerate(lines) if l.startswith('## Appendix 1'))
    a2 = next(i for i, l in enumerate(lines) if l.startswith('## Appendix 2'))
    t1, t2 = table(lines, a1), table(lines, a2)
    for name, t, n in (('1', t1, 99), ('2', t2, 97)):
        if len(t) != n or [r for r, _ in t] != list(range(n)):
            sys.exit('table %s : %d rows (want %d, in order)' % (name, len(t), n))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// currencies_gen.h -- GENERATED by scripts/gen_currencies.py from the client\'s own row tables\n')
        f.write('// (docs/notes/status-panels-b-re-2026-11-18.md, appendices 1 and 2). Do not hand-edit.\n')
        f.write('// Row r of Status -> Currencies (0x113) / Currencies 2 (0x118), in the client\'s on-screen order.\n')
        f.write('#pragma once\n\nnamespace aio {\n\n')
        for name, t in (('CURRENCY1', t1), ('CURRENCY2', t2)):
            f.write('static const int %s_N = %d;\n' % (name, len(t)))
            f.write('static const char* const %s_EN[%d] = {\n' % (name, len(t)))
            for _, lab in t:
                f.write('    %s,\n' % c_str(lab))
            f.write('};\n\n')
        f.write('} // namespace aio\n')
    print('currencies_gen.h : %d + %d rows' % (len(t1), len(t2)))


if __name__ == '__main__':
    main()
